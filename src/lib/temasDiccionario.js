export const ESTILOS_TEMA = ["sello", "jade", "bambu", "abanico", "tinta", "linterna"];

const HAN = /\p{Script=Han}/u;
/** Primer carácter chino de un texto (para sellos y emblemas). */
export function primerHan(texto, porDefecto = "词") {
  const m = String(texto || "").match(HAN);
  return m ? m[0] : porDefecto;
}

export function temaZh(tema) {
  return TEMAS_ZH[tema] || "";
}
