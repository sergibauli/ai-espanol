// Ámbito normalizado → clave de color y etiqueta bilingüe
const AMBITOS = {
  personal: ["personal", "Personal", "个人"],
  publico: ["publico", "Público", "公共"],
  profesional: ["profesional", "Profesional", "职场"],
  educativo: ["educativo", "Educativo", "教育"],
};
export function ambitoDe(a) {
  const k = String(a || "")
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase();
  if (k.startsWith("acad") || k.startsWith("educ")) return AMBITOS.educativo;
  return AMBITOS[k] || AMBITOS.personal;
}
